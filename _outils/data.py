def kind(r):
    n = r["needs"]
    if r.get("tool"): return "outils"
    if r["id"] in ("sos","infoaide"): return "lignes"
    if "hebergement" in n and r["id"] not in ("bouclier",): return "hebergement"
    if "juridique" in n and r["id"] in ("rebatir","dpcp","ivac","cavac"): return "juridique"
    if "immigration" in n: return "immigration"
    if r["id"] in ("banques","211","csf"): return "outils"
    return "soutien"

